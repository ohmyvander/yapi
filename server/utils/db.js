const { Pool } = require('pg');
const yapi = require('../yapi.js');
const { createModel } = require('./pgModel');

const modelCache = {};
const tableCache = {};
let pool = null;
let connectPromise = null;

const CORE_TABLES = [
  'user',
  'group',
  'project',
  'interface',
  'interface_cat',
  'interface_case',
  'interface_col',
  'log',
  'avatar',
  'token',
  'follow',
  'storage',
  'adv_mock',
  'adv_mock_case',
  'statis_mock',
  'wiki',
  'interface_auto_sync'
];

function quoteIdent(name) {
  if (!/^[a-zA-Z_][a-zA-Z0-9_]*$/.test(name)) {
    throw new Error('Invalid PostgreSQL identifier: ' + name);
  }
  return '"' + name + '"';
}

function indexName(table, suffix) {
  return (table + '_' + suffix).replace(/[^a-zA-Z0-9_]/g, '_');
}

function getPoolConfig() {
  const db = yapi.WEBCONFIG.db || {};
  const poolOptions = db.pool || {};
  const config = {
    host: db.host || db.servername || '127.0.0.1',
    port: Number(db.port || 5432),
    database: db.database || db.DATABASE || 'yapi',
    user: db.user,
    password: db.password || db.pass,
    ssl: db.ssl || false,
    max: poolOptions.max || db.max || 10,
    idleTimeoutMillis: poolOptions.idleTimeoutMillis || 30000
  };

  Object.keys(config).forEach(key => {
    if (config[key] === undefined || config[key] === '') {
      delete config[key];
    }
  });

  return config;
}

function model(name, schema) {
  if (!modelCache[name]) {
    modelCache[name] = createModel(name, schema || {}, dbApi);
  }
  return modelCache[name];
}

async function query(sql, params) {
  if (!pool) {
    await connect();
  }
  return pool.query(sql, params);
}

async function transaction(callback) {
  if (!pool) {
    await connect();
  }

  const client = await pool.connect();
  try {
    await client.query('BEGIN');
    const result = await callback(client);
    await client.query('COMMIT');
    return result;
  } catch (err) {
    await client.query('ROLLBACK');
    throw err;
  } finally {
    client.release();
  }
}

async function ensureTable(name) {
  if (tableCache[name]) {
    return;
  }

  await query(
    `CREATE TABLE IF NOT EXISTS ${quoteIdent(name)} (
      _id integer GENERATED BY DEFAULT AS IDENTITY (START WITH 11 INCREMENT BY 1) PRIMARY KEY,
      data jsonb NOT NULL DEFAULT '{}'::jsonb,
      created_at timestamptz NOT NULL DEFAULT now(),
      updated_at timestamptz NOT NULL DEFAULT now()
    )`
  );

  await query(
    `CREATE INDEX IF NOT EXISTS ${quoteIdent(indexName(name, 'data_gin_idx'))}
      ON ${quoteIdent(name)} USING gin (data jsonb_path_ops)`
  );

  tableCache[name] = true;
}

async function createJsonIndex(table, field, options) {
  options = options || {};
  const unique = options.unique ? 'UNIQUE ' : '';
  const suffix = field.replace(/\./g, '_') + (options.unique ? '_uniq' : '_idx');
  await query(
    `CREATE ${unique}INDEX IF NOT EXISTS ${quoteIdent(indexName(table, suffix))}
      ON ${quoteIdent(table)} ((data #>> '{${field.replace(/\./g, ',')}}'))`
  );
}

async function initSchema() {
  for (let i = 0; i < CORE_TABLES.length; i++) {
    await ensureTable(CORE_TABLES[i]);
  }

  await createJsonIndex('user', 'username');
  await createJsonIndex('user', 'email', { unique: true });
  await createJsonIndex('project', 'uid');
  await createJsonIndex('project', 'name');
  await createJsonIndex('project', 'group_id');
  await createJsonIndex('log', 'uid');
  await createJsonIndex('log', 'typeid');
  await createJsonIndex('log', 'type');
  await createJsonIndex('interface_col', 'uid');
  await createJsonIndex('interface_col', 'project_id');
  await createJsonIndex('interface_cat', 'uid');
  await createJsonIndex('interface_cat', 'project_id');
  await createJsonIndex('interface_case', 'uid');
  await createJsonIndex('interface_case', 'col_id');
  await createJsonIndex('interface_case', 'project_id');
  await createJsonIndex('interface', 'uid');
  await createJsonIndex('interface', 'path');
  await createJsonIndex('interface', 'method');
  await createJsonIndex('interface', 'project_id');
  await createJsonIndex('group', 'uid');
  await createJsonIndex('group', 'group_name');
  await createJsonIndex('avatar', 'uid');
  await createJsonIndex('token', 'project_id');
  await createJsonIndex('follow', 'uid');
  await createJsonIndex('follow', 'projectid');
  await createJsonIndex('storage', 'key', { unique: true });
}

function connect(callback) {
  if (!connectPromise) {
    pool = new Pool(getPoolConfig());
    connectPromise = pool
      .query('SELECT 1')
      .then(function() {
        yapi.commons.log('postgresql load success...');
        if (typeof callback === 'function') {
          callback.call(pool);
        }
        return pool;
      })
      .catch(function(err) {
        yapi.commons.log(err + ' postgresql connect error', 'error');
        throw err;
      });
  }

  return connectPromise;
}

const dbApi = {
  quoteIdent,
  query,
  ensureTable
};

yapi.db = model;

module.exports = {
  model,
  connect,
  query,
  transaction,
  ensureTable,
  initSchema,
  getPool: function() {
    return pool;
  }
};
